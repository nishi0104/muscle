  // 種目解説を表示する関数
  function showExerciseGuide(res, exerciseName) {
    // 曖昧検索用の関数
    function findExercise(name) {
      // 完全一致を最初に試す
      if (exerciseGuides[name]) {
        return name;
      }
      
      // 部分一致で検索
      var exercises = Object.keys(exerciseGuides);
      for (var i = 0; i < exercises.length; i++) {
        if (name.indexOf(exercises[i]) !== -1 || exercises[i].indexOf(name) !== -1) {
          return exercises[i];
        }
      }
      
      return null;
    }
    
    var foundExercise = findExercise(exerciseName);
    var guide = foundExercise ? exerciseGuides[foundExercise] : null;
    
    if (guide) {
      var response = foundExercise + 'の正しいフォーム\n\n';
      response += guide.description + '\n\n';
      
      response += '基本フォーム\n';
      for (var i = 0; i < guide.form.length; i++) {
        response += guide.form[i] + '\n';
      }
      
      response += '\nコツとポイント\n';
      for (var i = 0; i < guide.tips.length; i++) {
        response += '• ' + guide.tips[i] + '\n';
      }
      
      response += '\n 正しいフォームで安全にトレーニングしましょう！';
      res.send(response);
    } else {
      res.send('「' + exerciseName + '」の解説はまだ準備中です。\n他の種目について聞いてみてください！');
    }
  }

  // 「〜について教えて」パターン（hearのみ使用）
